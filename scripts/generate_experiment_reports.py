def _style(doc):
    normal = doc.styles["Normal"]
    normal.font.name = "宋体"
    normal.font.size = Pt(11)
    normal._element.rPr.rFonts.set(qn("w:eastAsia"), "宋体")


def _cover(doc, title, course):
    for _ in range(4):
        doc.add_paragraph("")
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run(course)
    run.font.size = Pt(16)
    run.font.bold = True

    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run(title)
    run.font.size = Pt(22)
    run.font.bold = True
    run.font.color.rgb = RGBColor(0x1F, 0x3A, 0x8A)

    for _ in range(3):
        doc.add_paragraph("")

    table = doc.add_table(rows=4, cols=2)
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    info = [("姓　　名", NAME), ("学　　号", SID), ("班　　级", CLASS_NAME), ("日　　期", DATE)]
    for i, (k, v) in enumerate(info):
        table.cell(i, 0).text = k
        table.cell(i, 1).text = v
        for col in (0, 1):
            para = table.cell(i, col).paragraphs[0]
            para.alignment = WD_ALIGN_PARAGRAPH.CENTER
            for r in para.runs:
                r.font.size = Pt(12)
    doc.add_page_break()


def _h(doc, text, level=1):
    p = doc.add_heading(text, level=level)
    for run in p.runs:
        run.font.name = "黑体"
        run._element.rPr.rFonts.set(qn("w:eastAsia"), "黑体")
    return p


def _p(doc, text):
    """段落。支持 **加粗** 行内标记（成对出现时才解析）。"""
    para = doc.add_paragraph()
    para.paragraph_format.space_after = Pt(4)
    if text.count("**") >= 2 and text.count("**") % 2 == 0:
        for i, part in enumerate(text.split("**")):
            if not part:
                continue
            run = para.add_run(part)
            if i % 2 == 1:
                run.font.bold = True
    else:
        para.add_run(text)
    return para


def _bullets(doc, items):
    for item in items:
        doc.add_paragraph(item, style="List Bullet")


def _table(doc, header, rows, widths=None):
    table = doc.add_table(rows=1, cols=len(header))
    table.style = "Table Grid"
    for i, text in enumerate(header):
        cell = table.rows[0].cells[i]
        cell.text = text
        for para in cell.paragraphs:
            for run in para.runs:
                run.font.bold = True
                run.font.size = Pt(10)
    for row in rows:
        cells = table.add_row().cells
        for i, value in enumerate(row):
            cells[i].text = str(value)
            for para in cells[i].paragraphs:
                for run in para.runs:
                    run.font.size = Pt(10)
    doc.add_paragraph("")
    return table


def _img(doc, filename, caption, width_cm=16.2):
    """插入按教材符号绘制的设计图（居中）+ 图号说明。"""
    from docx.shared import Cm
    path = os.path.join(DIAGRAMS, filename)
    if not os.path.exists(path):
        raise FileNotFoundError(
            "设计图缺失：%s（请先运行 python scripts/draw_diagrams.py）" % path)
    para = doc.add_paragraph()
    para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    para.paragraph_format.space_before = Pt(6)
    para.paragraph_format.space_after = Pt(2)
    para.add_run().add_picture(path, width=Cm(width_cm))
    cap = doc.add_paragraph()
    cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = cap.add_run(caption)
    run.font.size = Pt(9)
    run.font.color.rgb = RGBColor(0x47, 0x55, 0x69)
    cap.paragraph_format.space_after = Pt(8)
    return para


def build(path, course, title, sections):
    doc = Document()
    _style(doc)
    _cover(doc, title, course)
    for block in sections:
        kind = block[0]
        if kind == "h":
            _h(doc, block[1], block[2] if len(block) > 2 else 1)
        elif kind == "p":
            _p(doc, block[1])
        elif kind == "b":
            _bullets(doc, block[1])
        elif kind == "t":
            _table(doc, block[1], block[2])
        elif kind == "img":
            _img(doc, block[1], block[2], block[3] if len(block) > 3 else 16.2)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    doc.save(path)
    print("[OK]", path)


